#!/usr/bin/env python3
"""Generate the FairPlay lookup-table blob for the Kotlin port.

The FairPlay ("playfair") algorithm needs a large set of fixed lookup tables.
They are extracted from the Python reference implementation (fairplay3.py,
GPLv2, by systemcrash / based on OmgHax) so that the Kotlin port does not have
to inline hundreds of kilobytes of hex literals.

Usage:
    python3 tools/fairplay_gen.py [path/to/fairplay3.py] [out.kt] [out.bin]

Defaults:
    reference : ../../_ref/fairplay3.py relative to this script
    out.kt    : core/src/main/kotlin/com/airplaytv/core/fairplay/FairPlayTableData.kt
    out.bin   : not written unless explicitly requested

The default Kotlin output embeds the blob as base64 chunks. This project's
Gradle build registers `src/main/resources` twice, so any resource file is
rejected as a duplicate; embedding keeps the table data out of the JVM method
bytecode limits while avoiding that build-configuration conflict. If `out.bin`
is supplied, a binary resource with the documented layout is produced too.

Binary layout (little-endian), matching FairPlayTables.kt:
    offset 0   : magic  "FPTB"
    offset 4   : u32 version = 1
    offset 8   : u32 payload length in bytes
    offset 12  : u32 CRC-32 (zlib) of the payload
    offset 16  : payload, tables in the order listed in PAYLOAD below

All multi-byte unsigned 32-bit tables are stored little-endian, matching the
C `uint32_t` arrays on the little-endian targets Apple uses.
"""

import base64
import importlib.util
import os
import struct
import sys
import zlib

# (attribute name in fairplay3, element kind, element count)
# kind "u8" -> one byte per element, "u32" -> four little-endian bytes.
PAYLOAD = [
    ("table_s1", "u8", 10240),
    ("table_s2", "u8", 36864),
    ("table_s3", "u8", 4096),
    ("table_s4", "u8", 36864),
    ("table_s5", "u32", 256),
    ("table_s6", "u32", 256),
    ("table_s7", "u32", 256),
    ("table_s8", "u32", 256),
    ("table_s9", "u32", 1024),
    ("table_s10", "u8", 4096),
    ("message_key", "u8", 4 * 144),
    ("message_iv", "u8", 4 * 16),
    ("z_key", "u8", 16),
    ("x_key", "u8", 16),
    ("t_key", "u8", 16),
    ("indexMangle", "u8", 11),
    ("static_source_1", "u8", 17),
    ("static_source_2", "u8", 47),
    ("initial_session_key", "u8", 16),
    ("default_sap", "u8", 276),
]

MAGIC = b"FPTB"
VERSION = 1
HEADER_SIZE = 16
CHUNK_CHARS = 20000


def load_reference(path):
    spec = importlib.util.spec_from_file_location("fairplay3_ref", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def flatten(values):
    out = []
    for v in values:
        if isinstance(v, (list, tuple, bytearray, bytes)):
            out.extend(v)
        else:
            out.append(v)
    return out


def build_payload(mod):
    payload = bytearray()
    for name, kind, count in PAYLOAD:
        values = flatten(getattr(mod, name))
        if len(values) != count:
            raise SystemExit(
                "table %s: expected %d elements, reference has %d" % (name, count, len(values))
            )
        if kind == "u8":
            for v in values:
                if not 0 <= v <= 0xFF:
                    raise SystemExit("table %s: value 0x%x out of byte range" % (name, v))
                payload.append(v)
        else:
            for v in values:
                if not 0 <= v <= 0xFFFFFFFF:
                    raise SystemExit("table %s: value 0x%x out of uint32 range" % (name, v))
                payload += struct.pack("<I", v)
    return bytes(payload)


def build_header(payload):
    return MAGIC + struct.pack(
        "<III", VERSION, len(payload), zlib.crc32(payload) & 0xFFFFFFFF
    )


def write_kotlin(path, blob):
    """Write a generated Kotlin object containing base64 chunks of `blob`."""
    encoded = base64.b64encode(blob).decode("ascii")
    chunks = [encoded[i:i + CHUNK_CHARS] for i in range(0, len(encoded), CHUNK_CHARS)]
    lines = [
        "// Generated by tools/fairplay_gen.py -- do not edit by hand.",
        "package com.airplaytv.core.fairplay",
        "",
        "/**",
        " * Base64-encoded FairPlay lookup tables (see FairPlayTables.kt for the layout).",
        " *",
        " * The blob is stored in short string chunks so that no single class-file",
        " * constant exceeds the JVM's 64 KiB UTF-8 limit, and decoded once on first use.",
        " * Decoding is implemented in pure Kotlin so the module has no dependency on",
        " * platform Base64 implementations.",
        " */",
        "internal object FairPlayTableData {",
        "    private val CHUNKS = arrayOf(",
    ]
    for chunk in chunks:
        lines.append('        "%s",' % chunk)
    lines += [
        "    )",
        "",
        "    fun decode(): ByteArray = decodeBase64(CHUNKS.joinToString(separator = \"\"))",
        "",
        "    private fun decodeBase64(text: String): ByteArray {",
        "        val out = ByteArray(text.length * 3 / 4)",
        "        var outPos = 0",
        "        var buffer = 0",
        "        var bits = 0",
        "        for (c in text) {",
        "            val value = when (c) {",
        "                in 'A'..'Z' -> c - 'A'",
        "                in 'a'..'z' -> c - 'a' + 26",
        "                in '0'..'9' -> c - '0' + 52",
        "                '+' -> 62",
        "                '/' -> 63",
        "                '=' -> continue",
        "                else -> error(\"invalid base64 character in FairPlay table data\")",
        "            }",
        "            buffer = (buffer shl 6) or value",
        "            bits += 6",
        "            if (bits >= 8) {",
        "                bits -= 8",
        "                out[outPos++] = (buffer ushr bits).toByte()",
        "            }",
        "        }",
        "        return if (outPos == out.size) out else out.copyOf(outPos)",
        "    }",
        "}",
        "",
    ]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))


def main(argv):
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.dirname(here)
    ref = argv[1] if len(argv) > 1 else os.path.join(repo, "..", "_ref", "fairplay3.py")
    kotlin_out = argv[2] if len(argv) > 2 else os.path.join(
        repo, "core", "src", "main", "kotlin", "com", "airplaytv", "core", "fairplay",
        "FairPlayTableData.kt",
    )
    bin_out = argv[3] if len(argv) > 3 else None
    ref = os.path.abspath(ref)
    if not os.path.isfile(ref):
        raise SystemExit("reference file not found: %s" % ref)

    mod = load_reference(ref)
    payload = build_payload(mod)
    header = build_header(payload)
    blob = header + payload

    write_kotlin(os.path.abspath(kotlin_out), blob)
    print("wrote %s (%d bytes of table data)" % (os.path.abspath(kotlin_out), len(blob)))
    if bin_out:
        bin_out = os.path.abspath(bin_out)
        os.makedirs(os.path.dirname(bin_out), exist_ok=True)
        with open(bin_out, "wb") as fh:
            fh.write(blob)
        print("wrote %s (%d bytes)" % (bin_out, len(blob)))


if __name__ == "__main__":
    main(sys.argv)
